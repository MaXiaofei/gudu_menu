#!/usr/bin/env node
/**
 * Design token 生成器：docs/design/tokens.json（唯一权威）→ 三端代码。
 *
 *   node scripts/design/gen-tokens.mjs           生成/覆盖三端产物
 *   node scripts/design/gen-tokens.mjs --check   只校验：产物与 tokens.json 不一致或皮肤不合规则退出码 1（CI 用）
 *
 * 产物（均为生成文件，禁止手改）：
 *   menu-flutter/lib/core/tokens.g.dart        皮肤注册表 kBrandSkins + 每套 AppTokens 常量 + 共享 scale
 *   menu-mini/src/styles/tokens.generated.ts   皮肤注册表 SKINS + CSS 变量映射 + 共享 scale
 *   menu-mini/src/styles/tokens.generated.css  `page{}` 默认皮肤 + 共享变量（App.vue 引入）
 *   menu-admin/src/styles/tokens.generated.ts  后台皮肤注册表（含旧 key 兼容）+ 功能色
 *
 * 换肤 = tokens.json color.theme 下新增一项 → 运行本脚本。校验规则见 validateSkins()。
 * 零依赖，Node ≥ 18。
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const TOKENS_PATH = resolve(ROOT, 'docs/design/tokens.json')

/** 每套皮肤必须提供的色值字段（顺序即生成顺序）。 */
export const PALETTE_KEYS = [
  'primary', 'primaryDeep', 'primarySoft', 'secondary', 'accent',
  'bg', 'card', 'border', 'title', 'body', 'caption', 'highlight', 'onPrimary',
]
const ADMIN_KEYS = ['sidebar', 'sidebarText', 'sidebarActiveBg']
const SKIN_KEY_RE = /^[a-z][a-zA-Z0-9]*$/
const HEX_RE = /^#[0-9A-Fa-f]{6}$/

/** palette key → CSS 变量名（与 menu-mini 现有 var(--xxx) 命名保持一致）。 */
export const CSS_VAR = {
  primary: '--primary', primaryDeep: '--primary-deep', primarySoft: '--primary-soft',
  secondary: '--secondary', accent: '--accent', bg: '--bg', card: '--card', border: '--border',
  title: '--title', body: '--body', caption: '--caption', highlight: '--highlight',
  onPrimary: '--on-primary',
}

// ---------------------------------------------------------------- 读取与校验

export function loadTokens(path = TOKENS_PATH) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

/** 皮肤列表（保持 JSON 顺序，第一项为默认皮肤）。 */
export function skinsOf(tokens) {
  return Object.entries(tokens.color.theme)
    .filter(([k]) => !k.startsWith('$'))
    .map(([key, v]) => ({ key, ...v }))
}

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

/** WCAG 2.x 对比度。 */
export function contrast(a, b) {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (l1 + 0.05) / (l2 + 0.05)
}

/**
 * 可读性门禁（WCAG AA）：正文类文字 ≥ 4.5，辅助文字 ≥ 3。
 * 主色底白字是品牌按钮惯例，属于「大号粗体」场景，按 ≥ 2.2 的品牌底线只告警不阻断。
 */
export const CONTRAST_RULES = [
  { fg: 'title', bg: 'bg', min: 4.5 }, { fg: 'title', bg: 'card', min: 4.5 },
  { fg: 'body', bg: 'bg', min: 4.5 }, { fg: 'body', bg: 'card', min: 4.5 },
  { fg: 'caption', bg: 'card', min: 2.5 },
  { fg: 'onPrimary', bg: 'primaryDeep', min: 3 },
]

/** 返回 { errors, warnings }。errors 非空则拒绝生成。 */
export function validateSkins(tokens) {
  const errors = []
  const warnings = []
  const skins = skinsOf(tokens)
  if (skins.length === 0) errors.push('color.theme 至少需要一套皮肤')
  const legacy = new Set()
  for (const s of skins) {
    const at = `皮肤 ${s.key}`
    if (!SKIN_KEY_RE.test(s.key)) errors.push(`${at}: key 只能是小驼峰字母数字`)
    if (!s.label) errors.push(`${at}: 缺少 label`)
    for (const k of PALETTE_KEYS) {
      if (!HEX_RE.test(s[k] ?? '')) errors.push(`${at}: ${k} 必须是 #RRGGBB，当前 ${s[k]}`)
    }
    if (!/^\d{1,3},\d{1,3},\d{1,3}$/.test(s.shadowRgb ?? '')) errors.push(`${at}: shadowRgb 必须形如 169,101,30`)
    for (const k of ADMIN_KEYS) {
      if (!HEX_RE.test(s.admin?.[k] ?? '')) errors.push(`${at}: admin.${k} 必须是 #RRGGBB`)
    }
    if (!Array.isArray(s.chart) || s.chart.length < 3 || !s.chart.every((c) => HEX_RE.test(c))) {
      errors.push(`${at}: chart 至少 3 个 #RRGGBB 色值`)
    }
    if (s.legacyKey) {
      if (legacy.has(s.legacyKey)) errors.push(`${at}: legacyKey ${s.legacyKey} 重复`)
      legacy.add(s.legacyKey)
    }
    if (errors.length) continue
    for (const r of CONTRAST_RULES) {
      const c = contrast(s[r.fg], s[r.bg])
      if (c < r.min) errors.push(`${at}: ${r.fg} 在 ${r.bg} 上对比度 ${c.toFixed(2)} < ${r.min}`)
    }
    const btn = contrast(s.onPrimary, s.primary)
    if (btn < 2.2) errors.push(`${at}: 主色按钮文字对比度 ${btn.toFixed(2)} < 2.2，按钮不可读`)
    else if (btn < 3) warnings.push(`${at}: 主色按钮文字对比度 ${btn.toFixed(2)}（< 3，仅适合大号粗体文字）`)
  }
  return { errors, warnings }
}

// ---------------------------------------------------------------- 生成

const HEADER = (src) =>
  `GENERATED by scripts/design/gen-tokens.mjs from ${src} — DO NOT EDIT.\n` +
  'Run `node scripts/design/gen-tokens.mjs` after changing tokens.json.'

const dartColor = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`
const rgbToHex = (rgb) => '#' + rgb.split(',').map((n) => Number(n).toString(16).padStart(2, '0')).join('')
const dartStr = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const tsStr = (s) => JSON.stringify(String(s))
const numericScale = (obj) => Object.entries(obj).filter(([k, v]) => !k.startsWith('$') && typeof v === 'number')

export function genFlutter(tokens) {
  const skins = skinsOf(tokens)
  const sem = Object.entries(tokens.color.semantic).filter(([k]) => !k.startsWith('$'))
  const out = []
  out.push(`// ${HEADER('docs/design/tokens.json').replace(/\n/g, '\n// ')}`)
  out.push('// ignore_for_file: constant_identifier_names')
  out.push('')
  out.push("import 'package:flutter/painting.dart';")
  out.push('')
  out.push("import 'app_theme.dart';")
  out.push('')
  out.push('/// 一套皮肤的元数据 + token。顺序与 tokens.json 一致，第一项为默认皮肤。')
  out.push('class BrandSkin {')
  out.push('  const BrandSkin({required this.key, required this.label, required this.tagline, required this.tokens, required this.onPrimary, required this.chart});')
  out.push('  /// 持久化用的稳定 key（如 cream / matcha）。')
  out.push('  final String key;')
  out.push('  final String label;')
  out.push('  final String tagline;')
  out.push('  final AppTokens tokens;')
  out.push('  /// 主色底上的文字/图标色。')
  out.push('  final Color onPrimary;')
  out.push('  /// 图表多序列配色。')
  out.push('  final List<Color> chart;')
  out.push('}')
  out.push('')
  for (const s of skins) {
    out.push(`/// ${s.label}：${s.tagline ?? ''}`)
    out.push(`const AppTokens kSkin_${s.key} = AppTokens(`)
    for (const k of PALETTE_KEYS.filter((k) => k !== 'onPrimary')) out.push(`  ${k}: ${dartColor(s[k])},`)
    out.push(`  shadowBase: ${dartColor(rgbToHex(s.shadowRgb))},`)
    out.push(');')
    out.push('')
  }
  out.push('/// 皮肤注册表。')
  out.push('const List<BrandSkin> kBrandSkins = [')
  for (const s of skins) {
    out.push('  BrandSkin(')
    out.push(`    key: ${dartStr(s.key)},`)
    out.push(`    label: ${dartStr(s.label)},`)
    out.push(`    tagline: ${dartStr(s.tagline ?? '')},`)
    out.push(`    tokens: kSkin_${s.key},`)
    out.push(`    onPrimary: ${dartColor(s.onPrimary)},`)
    out.push(`    chart: [${s.chart.map(dartColor).join(', ')}],`)
    out.push('  ),')
  }
  out.push('];')
  out.push('')
  out.push('/// 按 key 取皮肤；未知 key 回落默认皮肤。')
  out.push('BrandSkin brandSkinOf(String? key) =>')
  out.push('    kBrandSkins.firstWhere((s) => s.key == key, orElse: () => kBrandSkins.first);')
  out.push('')
  out.push('/// 全皮肤共享的功能色。')
  out.push('abstract final class GenSemantic {')
  for (const [k, v] of sem) out.push(`  static const Color ${k} = ${dartColor(v)};`)
  out.push('}')
  out.push('')
  out.push('/// 圆角阶梯（逻辑像素）。')
  out.push('abstract final class GenRadius {')
  for (const [k, v] of numericScale(tokens.radius)) out.push(`  static const double ${k} = ${v};`)
  out.push('}')
  out.push('')
  out.push('/// 间距阶梯（逻辑像素）。')
  out.push('abstract final class GenSpacing {')
  for (const [k, v] of numericScale(tokens.spacing)) out.push(`  static const double ${k} = ${v};`)
  out.push('}')
  out.push('')
  out.push('/// 动效时长。')
  out.push('abstract final class GenMotion {')
  for (const [k, v] of Object.entries(tokens.motion.duration)) {
    out.push(`  static const Duration ${k} = Duration(milliseconds: ${parseInt(v, 10)});`)
  }
  out.push('}')
  out.push('')
  return out.join('\n')
}

function tsObject(obj, indent = '  ') {
  return '{\n' + Object.entries(obj).map(([k, v]) => `${indent}${k}: ${typeof v === 'number' ? v : tsStr(v)},`).join('\n') + '\n}'
}

export function genMiniTs(tokens) {
  const skins = skinsOf(tokens)
  const sem = Object.fromEntries(Object.entries(tokens.color.semantic).filter(([k]) => !k.startsWith('$')))
  const out = []
  out.push(`/**\n * ${HEADER('docs/design/tokens.json').replace(/\n/g, '\n * ')}\n */`)
  out.push('')
  out.push('/** 一套皮肤的色板（与 CSS 变量一一对应，见 SKIN_CSS_VARS）。 */')
  out.push('export interface SkinPalette {')
  for (const k of PALETTE_KEYS) out.push(`  ${k}: string`)
  out.push('  /** 阴影基色 RGB，如 "169,101,30"（CSS 变量 --sh）。 */')
  out.push('  shadowRgb: string')
  out.push('}')
  out.push('')
  out.push('export interface SkinDef {')
  out.push('  key: string')
  out.push('  label: string')
  out.push('  tagline: string')
  out.push('  palette: SkinPalette')
  out.push('  chart: string[]')
  out.push('}')
  out.push('')
  out.push('/** 皮肤注册表（第一项为默认皮肤）。 */')
  out.push('export const SKINS: SkinDef[] = [')
  for (const s of skins) {
    const palette = Object.fromEntries([...PALETTE_KEYS.map((k) => [k, s[k]]), ['shadowRgb', s.shadowRgb]])
    out.push('  {')
    out.push(`    key: ${tsStr(s.key)},`)
    out.push(`    label: ${tsStr(s.label)},`)
    out.push(`    tagline: ${tsStr(s.tagline ?? '')},`)
    out.push(`    palette: ${tsObject(palette, '      ').replace(/\n}$/, '\n    }')},`)
    out.push(`    chart: [${s.chart.map(tsStr).join(', ')}],`)
    out.push('  },')
  }
  out.push(']')
  out.push('')
  out.push(`export const DEFAULT_SKIN = ${tsStr(skins[0].key)}`)
  out.push('')
  out.push('/** palette 字段 → CSS 变量名。 */')
  out.push(`export const SKIN_CSS_VARS: Record<keyof SkinPalette, string> = ${tsObject({ ...CSS_VAR, shadowRgb: '--sh' })}`)
  out.push('')
  out.push('/** 全皮肤共享的功能色。 */')
  out.push(`export const SEMANTIC = ${tsObject(sem)} as const`)
  out.push('')
  out.push(`export const RADIUS = ${tsObject(Object.fromEntries(numericScale(tokens.radius)))} as const`)
  out.push('')
  out.push(`export const SPACING = ${tsObject(Object.fromEntries(numericScale(tokens.spacing)))} as const`)
  out.push('')
  out.push('/** 皮肤 → CSS 变量声明串（page-meta page-style / H5 全局 style 用）。 */')
  out.push('export function skinCssVars(key: string): string {')
  out.push('  const skin = SKINS.find((s) => s.key === key) ?? SKINS[0]')
  out.push('  return (Object.keys(SKIN_CSS_VARS) as (keyof SkinPalette)[])')
  out.push('    .map((k) => `${SKIN_CSS_VARS[k]}:${skin.palette[k]}`)')
  out.push("    .join(';')")
  out.push('}')
  out.push('')
  return out.join('\n')
}

export function genMiniCss(tokens) {
  const def = skinsOf(tokens)[0]
  const sem = Object.entries(tokens.color.semantic).filter(([k]) => !k.startsWith('$'))
  const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
  const lines = []
  lines.push(`/* ${HEADER('docs/design/tokens.json')} */`)
  lines.push(`/* 默认皮肤：${def.label}（运行时换肤由 utils/theme.ts 覆盖皮肤变量） */`)
  lines.push('page {')
  for (const k of PALETTE_KEYS) lines.push(`  ${CSS_VAR[k]}: ${def[k]};`)
  lines.push(`  --sh: ${def.shadowRgb};`)
  for (const [k, v] of sem) lines.push(`  --${kebab(k)}: ${v};`)
  for (const [k, v] of numericScale(tokens.radius)) lines.push(`  --radius-${k}: ${v}px;`)
  for (const [k, v] of numericScale(tokens.spacing)) lines.push(`  --space-${k}: ${v}px;`)
  for (const [k, v] of Object.entries(tokens.motion.duration)) lines.push(`  --dur-${k}: ${v};`)
  for (const [k, v] of Object.entries(tokens.motion.easing)) lines.push(`  --ease-${k}: ${v};`)
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

export function genAdminTs(tokens) {
  const skins = skinsOf(tokens)
  const sem = Object.fromEntries(Object.entries(tokens.color.semantic).filter(([k]) => !k.startsWith('$')))
  const out = []
  out.push(`/**\n * ${HEADER('docs/design/tokens.json').replace(/\n/g, '\n * ')}\n */`)
  out.push('')
  out.push('export interface AdminSkin {')
  out.push('  key: string')
  out.push('  /** 旧版持久化 key（如 warm/green），读取 localStorage 时兼容。 */')
  out.push('  legacyKey: string | null')
  out.push('  name: string')
  out.push('  tagline: string')
  for (const k of PALETTE_KEYS) out.push(`  ${k}: string`)
  for (const k of ADMIN_KEYS) out.push(`  ${k}: string`)
  out.push('  shadowRgb: string')
  out.push('  chart: string[]')
  out.push('}')
  out.push('')
  out.push('/** 后台皮肤注册表（第一项为默认皮肤）。 */')
  out.push('export const ADMIN_SKINS: AdminSkin[] = [')
  for (const s of skins) {
    out.push('  {')
    out.push(`    key: ${tsStr(s.key)},`)
    out.push(`    legacyKey: ${s.legacyKey ? tsStr(s.legacyKey) : 'null'},`)
    out.push(`    name: ${tsStr(s.label)},`)
    out.push(`    tagline: ${tsStr(s.tagline ?? '')},`)
    for (const k of PALETTE_KEYS) out.push(`    ${k}: ${tsStr(s[k])},`)
    for (const k of ADMIN_KEYS) out.push(`    ${k}: ${tsStr(s.admin[k])},`)
    out.push(`    shadowRgb: ${tsStr(s.shadowRgb)},`)
    out.push(`    chart: [${s.chart.map(tsStr).join(', ')}],`)
    out.push('  },')
  }
  out.push(']')
  out.push('')
  out.push('/** 按 key（或旧 key）取皮肤；未知回落默认。 */')
  out.push('export function adminSkinOf(key: string | null | undefined): AdminSkin {')
  out.push('  return ADMIN_SKINS.find((s) => s.key === key || s.legacyKey === key) ?? ADMIN_SKINS[0]')
  out.push('}')
  out.push('')
  out.push('/** 全皮肤共享的功能色。 */')
  out.push(`export const ADMIN_SEMANTIC = ${tsObject(sem)} as const`)
  out.push('')
  return out.join('\n')
}

export const OUTPUTS = [
  { path: 'menu-flutter/lib/core/tokens.g.dart', gen: genFlutter },
  { path: 'menu-mini/src/styles/tokens.generated.ts', gen: genMiniTs },
  { path: 'menu-mini/src/styles/tokens.generated.css', gen: genMiniCss },
  { path: 'menu-admin/src/styles/tokens.generated.ts', gen: genAdminTs },
]

// ---------------------------------------------------------------- CLI

function main(argv) {
  const check = argv.includes('--check')
  const tokens = loadTokens()
  const { errors, warnings } = validateSkins(tokens)
  warnings.forEach((w) => console.warn(`⚠️  ${w}`))
  if (errors.length) {
    errors.forEach((e) => console.error(`❌ ${e}`))
    process.exit(1)
  }
  let stale = 0
  for (const o of OUTPUTS) {
    const abs = resolve(ROOT, o.path)
    const content = o.gen(tokens)
    if (check) {
      let cur = null
      try { cur = readFileSync(abs, 'utf8') } catch { /* missing */ }
      if (cur !== content) { console.error(`❌ 过期：${o.path}（请运行 node scripts/design/gen-tokens.mjs）`); stale++ }
    } else {
      mkdirSync(dirname(abs), { recursive: true })
      writeFileSync(abs, content)
      console.log(`✓ ${o.path}`)
    }
  }
  const n = skinsOf(tokens).length
  if (check && stale) process.exit(1)
  console.log(check ? `✓ 产物与 tokens.json 一致（${n} 套皮肤）` : `✓ 已生成（${n} 套皮肤）`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2))
}
