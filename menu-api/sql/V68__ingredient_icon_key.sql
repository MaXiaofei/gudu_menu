-- 2) 采购品类兜底
UPDATE ingredient i
JOIN sys_dict d ON d.id = i.purchase_category_id AND d.dict_group = 'purchase_category'
SET i.icon_key = CASE d.name
  WHEN '蔬菜' THEN 'cabbage'
  WHEN '水果' THEN 'tomato'
  WHEN '畜禽肉' THEN 'pork'
  WHEN '水产海鲜' THEN 'fish'
  WHEN '蛋类' THEN 'egg'
  WHEN '乳制品' THEN 'milk'
  WHEN '调味料' THEN 'sauce'
  WHEN '谷物主食' THEN 'rice'
  WHEN '坚果' THEN 'rice'
  WHEN '干菌藻' THEN 'mushroom'
  WHEN '速冻' THEN 'noodle'
  WHEN '饮料' THEN 'milk'
  WHEN '肉禽蛋' THEN 'pork'
  WHEN '肉类' THEN 'pork'
  WHEN '禽蛋' THEN 'egg'
  WHEN '水产' THEN 'fish'
  WHEN '调料' THEN 'sauce'
  WHEN '调味品' THEN 'sauce'
  WHEN '粮油' THEN 'rice'
  WHEN '主食' THEN 'rice'
  WHEN '米面粮油' THEN 'rice'
  WHEN '乳品' THEN 'milk'
  WHEN '奶制品' THEN 'milk'
  WHEN '豆制品' THEN 'tofu'
  WHEN '菌菇' THEN 'mushroom'
  WHEN '日用' THEN 'tissue'
  WHEN '其他' THEN 'tissue'
  ELSE NULL END
WHERE i.icon_key IS NULL;
