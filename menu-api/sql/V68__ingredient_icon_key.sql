  'ALTER TABLE ingredient ADD COLUMN icon_key VARCHAR(32) NULL COMMENT ''插画 key（docs/design/assets.json ing）'' AFTER name',
  'SELECT 1');
PREPARE stmt FROM @s; EXECUTE stmt; DEALLOCATE PREPARE stmt;

